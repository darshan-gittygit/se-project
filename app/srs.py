"""
Software Requirements Specification assembly (problem statement section 12).

build_blocks() turns a /agents/pipeline result into a small document model -
headings, paragraphs, lists and tables - and render_markdown() /
render_html() write the same model as Markdown or as a self-contained,
print-friendly HTML page (the browser's Print -> Save as PDF gives a PDF; no
Word or PDF library is used). No LLM call: the SRS only arranges content the
pipeline already produced. Every requirement row and generated item shows
the stakeholder statement it came from (section 12's last line), and the
document carries a "not a legal determination" notice and an approval-status
table in which everything is proposed or pending.

SrsStore keeps the last few pipeline results in memory so GET can serve them;
they are lost when the server restarts.
"""
import html
import uuid
from collections import OrderedDict
from datetime import datetime, timezone

from app.artefacts import all_requirements

NOTICE = ("Not a legal determination. Compliance content maps requirements to a small curated knowledge base of "
          "paraphrased principles, not verbatim law. High-impact interpretations must be approved by compliance or "
          "legal officers. Everything in this document is proposed and awaits human approval.")


# --- document model ------------------------------------------------------------

def H(level, text): return ("h", level, text)
def P(text): return ("p", text)
def UL(items): return ("ul", [i for i in items if i])
def TABLE(headers, rows): return ("table", headers, rows)
def NOTE(text): return ("note", text)


def _ids(ids): return ", ".join(ids) or "-"


def _source(s: dict) -> str:
    if s.get("statement"):
        return f'{s["stakeholder"]}: "{s["statement"]}"'
    return f'{s.get("stakeholder", "")}: no stakeholder statement; assumed: {"; ".join(s.get("assumptions") or []) or "-"}'


def _req_source(r: dict) -> str:
    return _source({"stakeholder": r.get("source_stakeholder", ""), "statement": r.get("source_text", ""),
                    "assumptions": r.get("assumptions", [])})


def _sources(item: dict) -> str:
    return " / ".join(f'{s["requirement_id"]}: {_source(s)}' for s in item.get("source_statements", [])) or "-"


def build_blocks(result: dict, generated_at: str | None = None) -> list[tuple]:
    req = result.get("requirements", {})
    reqs = all_requirements(req)
    art = result.get("artefacts", {})
    sdlc = result.get("sdlc_recommendation") or {}
    wf = result.get("sdlc_workflow") or {}
    mapping = result.get("compliance_mapping") or {}
    domain = req.get("domain_inferred", "Unknown domain")
    when = generated_at or datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    b = [H(1, f"Software Requirements Specification: {domain}"),
         P(f"Generated by Requora AI on {when}. Status: proposed (not approved)."), NOTE(NOTICE)]

    b += [H(2, "1. Introduction"),
          H(3, "1.1 Purpose"), P("This specification collects the requirements, compliance mapping, risks, SDLC "
                                 "recommendation and supporting artefacts generated for the scenario below, for review "
                                 "and approval by the project's stakeholders."),
          H(3, "1.2 Scope"), P(f"Domain: {domain}."), P(f"Scenario: {result.get('scenario', '')}"),
          H(3, "1.3 Project-level assumptions"), UL(req.get("assumptions", [])) if req.get("assumptions") else P("None stated.")]

    stakeholders: dict[str, list[str]] = {}
    for r in reqs:
        stakeholders.setdefault(r.get("source_stakeholder", "Unknown"), []).append(r["id"])
    b += [H(2, "2. Stakeholders and sources"),
          TABLE(["Stakeholder", "Requirements"], [[s, _ids(ids)] for s, ids in stakeholders.items()])]

    for num, (title, key) in enumerate((("Functional requirements", "functional_requirements"),
                                        ("Non-functional requirements", "non_functional_requirements")), start=3):
        rows = [[r["id"], r["requirement"], r.get("priority", ""), r.get("risk_level", ""),
                 ", ".join(r.get("categories", [])), r.get("confidence", ""), _ids(r.get("applicable_regulations", [])),
                 _req_source(r)] for r in req.get(key, [])]
        b += [H(2, f"{num}. {title}"),
              TABLE(["ID", "Requirement", "Priority", "Risk", "Categories", "Confidence", "Regulations", "Source statement"], rows),
              H(3, f"{num}.1 Acceptance criteria")]
        b += [UL([f"{r['id']}: {c}" for r in req.get(key, []) for c in r.get("acceptance_criteria", [])])]

    stories = art.get("user_stories", [])
    b += [H(2, "5. User stories"),
          TABLE(["ID", "User story", "Acceptance criteria", "Requirements", "Source statements"],
                [[s["id"], s["story"], " / ".join(s["acceptance_criteria"]), _ids(s["requirement_ids"]), _sources(s)]
                 for s in stories]) if stories else P("None generated.")]

    b.append(H(2, "6. Use cases"))
    for uc in art.get("use_cases", []) or []:
        b += [H(3, f"{uc['id']} {uc['name']}"),
              P(f"Primary actor: {uc['primary_actor']}. Requirements: {_ids(uc['requirement_ids'])}."),
              P("Preconditions: " + ("; ".join(uc["preconditions"]) or "none")),
              UL([f"{i}. {step}" for i, step in enumerate(uc["main_flow"], start=1)]),
              P("Alternative flows: " + ("; ".join(uc["alternative_flows"]) or "none")),
              P("Postconditions: " + ("; ".join(uc["postconditions"]) or "none")),
              P(f"Source statements: {_sources(uc)}")]
    if not art.get("use_cases"):
        b.append(P("None generated."))

    b.append(H(2, "7. Process workflows"))
    for pw in art.get("process_workflows", []) or []:
        b += [H(3, f"{pw['id']} {pw['name']}"),
              TABLE(["Step", "Actor", "Action"], [[str(i), s["actor"], s["action"]] for i, s in enumerate(pw["steps"], start=1)]),
              P(f"Requirements: {_ids(pw['requirement_ids'])}. Source statements: {_sources(pw)}")]
    if not art.get("process_workflows"):
        b.append(P("None generated."))

    data = art.get("data_requirements", [])
    b += [H(2, "8. Data requirements"),
          TABLE(["ID", "Entity", "Description", "Attributes", "Retention", "Requirements", "Source statements"],
                [[d["id"], d["entity"], d["description"], ", ".join(d["attributes"]), d["retention"] or "not stated",
                  _ids(d["requirement_ids"]), _sources(d)] for d in data]) if data else P("None generated.")]
    ifaces = art.get("interface_requirements", [])
    b += [H(2, "9. Interface requirements"),
          TABLE(["ID", "Name", "Type", "Description", "Requirements", "Source statements"],
                [[i["id"], i["name"], i["interface_type"], i["description"], _ids(i["requirement_ids"]), _sources(i)]
                 for i in ifaces]) if ifaces else P("None generated.")]

    ccm = art.get("compliance_control_matrix", [])
    b += [H(2, "10. Compliance-control matrix"), NOTE(mapping.get("notice", NOTICE)),
          TABLE(["Requirement", "Regulation", "Jurisdiction", "Version", "Required control", "Status", "Gap",
                 "Confidence", "Needs review"],
                [[c["requirement_id"], c["regulation"], c["jurisdiction"], c["version"], c["required_control"] or "-",
                  c["status"], c["compliance_gap"] or "-", c["confidence"], "yes" if c["needs_human_review"] else "no"]
                 for c in ccm]) if ccm else P("No knowledge-base mapping.")]

    risks = (result.get("risk_register") or {}).get("risks", [])
    b += [H(2, "11. Threat and risk register"),
          P((result.get("risk_register") or {}).get("scoring", "")),
          TABLE(["ID", "Risk", "Category", "Likelihood", "Impact", "Score", "Level", "Mitigation", "Requirements"],
                [[r["id"], r["description"], r["category"], str(r["likelihood"]), str(r["impact"]), str(r["score"]),
                  r["level"], r["mitigation"], _ids(r["linked_requirement_ids"])] for r in risks]) if risks else P("No register.")]

    b.append(H(2, "12. SDLC recommendation"))
    if sdlc:
        approval = sdlc.get("approval_required", {})
        b += [P(f"Recommended model: {sdlc['recommended_model']}" + (" (close call)." if sdlc.get("is_close_call") else ".")),
              TABLE(["Rank", "Model", "Score", "Why not"],
                    [[str(m.get("rank", i)), m["model"], m.get("percent", f"{m['score']}%"), m.get("why_not") or "recommended"]
                     for i, m in enumerate(sdlc.get("scored_models", []), start=1)]),
              UL([f"{k.replace('_', ' ').capitalize()}: {v}" for k, v in (sdlc.get("justification") or {}).items()]),
              P(approval.get("note", ""))]
    else:
        b.append(P("Not available."))

    b.append(H(2, f"13. Development workflow ({wf.get('model', 'not available')})"))
    if wf.get("notice"):
        b.append(P(wf["notice"]))
    for ph in wf.get("phases", []):
        rows = []
        for field, items in ph.items():
            if isinstance(items, list) and items:
                rows.append([field.replace("_", " ").capitalize(), " / ".join(
                    i["text"] + (f" (added for {_ids(i['requirement_ids'])})" if i["source"] == "scenario" else "")
                    for i in items)])
        b += [H(3, f"Phase {ph['order']}: {ph['name']}"), TABLE(["Field", "Items"], rows)]

    rtm = art.get("traceability_matrix", [])
    b += [H(2, "14. Requirements traceability matrix"),
          TABLE(["Requirement", "Source statement", "Compliance", "Risks", "User stories", "Use cases",
                 "Workflows / data / interfaces"],
                [[t["requirement_id"], _source(t["source"]),
                  ", ".join(f"{c['source']} ({c['status']})" for c in t["compliance_sources"]) or "-",
                  _ids(t["risk_ids"]), _ids(t["user_stories_ids"]), _ids(t["use_cases_ids"]),
                  _ids(t["process_workflows_ids"] + t["data_requirements_ids"] + t["interface_requirements_ids"])]
                 for t in rtm]) if rtm else P("Not available.")]

    reg = art.get("assumptions_register", {"assumptions": [], "dependencies": []})
    b += [H(2, "15. Assumptions and dependencies"),
          TABLE(["ID", "Assumption", "Scope", "Requirements"],
                [[a["id"], a["text"], a["scope"], _ids(a["requirement_ids"])] for a in reg["assumptions"]])
          if reg["assumptions"] else P("No assumptions recorded."),
          TABLE(["Requirement", "Depends on"], [[d["requirement_id"], _ids(d["depends_on"])] for d in reg["dependencies"]])
          if reg["dependencies"] else P("No dependencies recorded.")]

    issues = art.get("open_issues", [])
    b += [H(2, "16. Open issues"),
          TABLE(["ID", "Type", "Description", "Requirements", "Origin"],
                [[i["id"], i["type"], i["description"], _ids(i["requirement_ids"]), i["origin"]] for i in issues])
          if issues else P("No open issues.")]

    approvals = [[f"Requirement {r['id']}", r.get("approval_status", "proposed"), "Product owner, compliance officer"]
                 for r in reqs]
    if sdlc:
        approvals.append([f"SDLC model: {sdlc['recommended_model']}", sdlc.get("approval_required", {}).get("status", "pending"),
                          ", ".join(sdlc.get("approval_required", {}).get("approvers", []))])
    if mapping.get("review_count"):
        approvals.append([f"Compliance interpretations flagged for review ({mapping['review_count']})", "pending",
                          "Compliance or legal officers"])
    if art:
        approvals.append(["Generated artefacts (stories, use cases, workflows, data, interfaces)", "proposed",
                          "Business analyst, product owner"])
    if wf:
        approvals.append([f"Development workflow ({wf.get('model')})", "proposed",
                          "Project manager, architect, security team, compliance officer"])
    b += [H(2, "17. Approval status"), TABLE(["Item", "Status", "Approvers"], approvals), NOTE(NOTICE)]
    return b


# --- renderers -------------------------------------------------------------------

def _md_cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render_markdown(blocks: list[tuple]) -> str:
    out = []
    for block in blocks:
        kind = block[0]
        if kind == "h":
            out.append(f"{'#' * block[1]} {block[2]}")
        elif kind == "p":
            out.append(block[1])
        elif kind == "note":
            out.append(f"> **{block[1]}**")
        elif kind == "ul":
            out.append("\n".join(f"- {_md_cell(i)}" for i in block[1]) or "- (none)")
        elif kind == "table":
            headers, rows = block[1], block[2]
            lines = ["| " + " | ".join(_md_cell(h) for h in headers) + " |", "|" + "---|" * len(headers)]
            lines += ["| " + " | ".join(_md_cell(c) for c in row) + " |" for row in rows]
            out.append("\n".join(lines) if rows else "(none)")
        out.append("")
    return "\n".join(out)


CSS = """
body { font-family: Georgia, 'Times New Roman', serif; max-width: 960px; margin: 2em auto; padding: 0 1em; color: #111; line-height: 1.45; }
h1 { font-size: 1.7em; } h2 { margin-top: 1.6em; border-bottom: 1px solid #999; } h3 { margin-top: 1.2em; }
table { border-collapse: collapse; width: 100%; margin: 0.6em 0 1em; font-size: 0.85em; }
th, td { border: 1px solid #777; padding: 4px 6px; vertical-align: top; text-align: left; }
th { background: #eee; }
.note { border: 2px solid #333; padding: 0.6em 0.9em; font-weight: bold; margin: 1em 0; }
.toolbar { margin-bottom: 1em; }
@media print { .toolbar { display: none; } body { margin: 0; max-width: none; } tr, .note { page-break-inside: avoid; } h2 { page-break-after: avoid; } }
"""


def render_html(blocks: list[tuple]) -> str:
    title = next((b[2] for b in blocks if b[0] == "h" and b[1] == 1), "Software Requirements Specification")
    e = html.escape
    body = ['<div class="toolbar"><button onclick="window.print()">Print / Save as PDF</button></div>']
    for block in blocks:
        kind = block[0]
        if kind == "h":
            body.append(f"<h{block[1]}>{e(block[2])}</h{block[1]}>")
        elif kind == "p":
            body.append(f"<p>{e(block[1])}</p>")
        elif kind == "note":
            body.append(f'<div class="note">{e(block[1])}</div>')
        elif kind == "ul":
            body.append("<ul>" + "".join(f"<li>{e(str(i))}</li>" for i in block[1]) + "</ul>")
        elif kind == "table":
            if not block[2]:
                body.append("<p>(none)</p>")
                continue
            head = "".join(f"<th>{e(str(h))}</th>" for h in block[1])
            rows = "".join("<tr>" + "".join(f"<td>{e(str(c))}</td>" for c in row) + "</tr>" for row in block[2])
            body.append(f"<table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table>")
    return (f'<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8"><title>{e(title)}</title>'
            f"<style>{CSS}</style></head><body>\n" + "\n".join(body) + "\n</body></html>\n")


# --- in-memory store for GET downloads ---------------------------------------

class SrsStore:
    """Keeps the last `capacity` pipeline results so their SRS can be downloaded by id. Lost on restart."""

    def __init__(self, capacity: int = 20):
        self.capacity = capacity
        self._items: OrderedDict[str, dict] = OrderedDict()

    def put(self, result: dict) -> str:
        srs_id = uuid.uuid4().hex[:12]
        self._items[srs_id] = result
        while len(self._items) > self.capacity:
            self._items.popitem(last=False)
        return srs_id

    def get(self, srs_id: str) -> dict | None:
        return self._items.get(srs_id)
