"""
Tunes the compliance agent's relevance threshold against a hand-labelled set
(scripts/retrieval_labels.json). Needs the .env key, internet and a built
chroma_db/, so it is NOT part of the offline test suite.

    python -m scripts.tune_relevance_threshold            # print the report
    python -m scripts.tune_relevance_threshold --write    # also save docs/RAG_TUNING.md

What it does:
1. "Before": the old query format (domain + every requirement joined into one
   string) for each scenario group, top-5 chunks - the distances the agent
   used to see.
2. "After": one short query per requirement, in two candidate formats
   (requirement text alone, and "domain: requirement"), top-k chunks each.
3. Every (query, retrieved chunk) pair is labelled relevant when the chunk's
   source is listed for that query. Pairs with a source listed under
   borderline_sources for that query are excluded.
4. For thresholds 0.40-0.90 it computes precision, recall, F1 and F0.5.
   F0.5 weights precision twice as much as recall, because citing an
   irrelevant source is worse for a compliance tool than missing one.
   The format and threshold with the best F0.5 win (ties: lower threshold).
   The threshold is tuned on ALL sources, generic baseline included, because
   it decides which chunks reach the prompt and generic chunks are still cited.
5. For information it also reports the same sweep on domain-specific sources
   only, and kb_relevance per scenario under the old rule (any source counts)
   and the current rule (only domain-specific sources count), at the agent's
   RELEVANCE_THRESHOLD.
6. Domain applicability (knowledge_base/sources.json): each scenario/domain
   unit is classified with the agent's own classify_domains(), and the sweep
   is repeated on what the agent can actually cite - a pair counts as
   positive only if it is under the threshold AND its source applies to the
   unit's domain tags.
"""
import json
import statistics
import sys
from pathlib import Path

from app.rag.kb_metadata import applies, classify_domains
from app.rag.retriever import retrieve_many
from app.agents.compliance_agent import (
    GENERIC_SOURCES, RELEVANCE_THRESHOLD, RELEVANT_COVERAGE, TOP_K_PER_QUERY, kb_relevance_from, merge_retrieval,
)

LABELS = Path(__file__).resolve().parent / "retrieval_labels.json"
OUT = Path(__file__).resolve().parent.parent / "docs" / "RAG_TUNING.md"
THRESHOLDS = [round(0.40 + 0.01 * i, 2) for i in range(51)]
FORMATS = {
    "requirement only": lambda domain, text: text,
    "domain: requirement": lambda domain, text: f"{domain}: {text}" if domain else text,
}


def _load():
    groups = json.loads(LABELS.read_text(encoding="utf-8"))["groups"]
    queries = []
    for g in groups:
        for q in g["queries"]:
            queries.append(dict(q, group=g["name"], domain=q.get("domain", g["domain"]),
                                scenario=bool(g.get("scenario"))))
    return groups, queries


def _stats(values):
    if not values:
        return "n=0"
    v = sorted(values)
    q = statistics.quantiles(v, n=4) if len(v) > 1 else [v[0]] * 3
    return f"n={len(v)}, min {v[0]:.3f}, Q1 {q[0]:.3f}, median {q[1]:.3f}, Q3 {q[2]:.3f}, max {v[-1]:.3f}"


def _histogram(rows, lo=0.40, hi=1.00, width=0.05):
    lines = ["| Distance bucket | Relevant pairs | Irrelevant pairs |", "|---|---|---|"]
    b = lo
    while b < hi - 1e-9:
        rel = sum(1 for d, lab in rows if lab and b <= d < b + width)
        irr = sum(1 for d, lab in rows if not lab and b <= d < b + width)
        lines.append(f"| {b:.2f}-{b + width:.2f} | {'#' * rel} {rel} | {'#' * irr} {irr} |")
        b += width
    return "\n".join(lines)


def _score(pairs, queries_by_key, t):
    tp = sum(1 for d, lab in pairs if lab and d < t)
    fp = sum(1 for d, lab in pairs if not lab and d < t)
    fn = sum(1 for d, lab in pairs if lab and d >= t)
    p = tp / (tp + fp) if tp + fp else 1.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    f05 = 1.25 * p * r / (0.25 * p + r) if p + r else 0.0
    # queries labelled "nothing applies" that would still get a citation
    neg = [k for k, q in queries_by_key.items() if not q["relevant"]]
    false_alarm = sum(1 for k in neg if queries_by_key[k]["min_d"] < t)
    return {"t": t, "tp": tp, "fp": fp, "fn": fn, "p": p, "r": r, "f1": f1, "f05": f05,
            "false_alarm": f"{false_alarm}/{len(neg)}"}


def main(write=False):
    groups, queries = _load()
    out = ["# Relevance threshold tuning", "",
           "Generated by `python -m scripts.tune_relevance_threshold --write` from "
           "`scripts/retrieval_labels.json`. Distances are ChromaDB squared L2 on unit-length "
           "Gemini embeddings (lower = closer; d = 2 - 2cos).", ""]

    # 1. Before: one long concatenated query per scenario
    scen = [g for g in groups if g.get("scenario")]
    long_q = [g["domain"] + ". " + " ".join(q["text"] for q in g["queries"]) for g in scen]
    before = retrieve_many(long_q, top_k=5)
    out += ["## Before: one concatenated query per scenario (old agent, top 5)", ""]
    all_before = []
    for g, chunks in zip(scen, before):
        ds = [c["distance"] for c in chunks]
        all_before += ds
        out.append(f"- {g['name']}: " + ", ".join(f"{c['source']} {c['distance']:.3f}" for c in chunks))
    out += ["", f"All: {_stats(all_before)}. Under the old 0.65 threshold: "
            f"{sum(d < 0.65 for d in all_before)} of {len(all_before)}.", ""]

    # 2-4. After: per-requirement queries in each candidate format
    best = None
    format_results = {}
    for fname, fmt in FORMATS.items():
        texts = [fmt(q["domain"], q["text"]) for q in queries]
        results = retrieve_many(texts, top_k=TOP_K_PER_QUERY)
        pairs, borderline, by_key, dom_pairs = [], [], {}, []
        for q, chunks in zip(queries, results):
            key = (q["group"], q["id"])
            unsure = set(q.get("borderline_sources", []))
            clear = [c["distance"] for c in chunks if c["source"] not in unsure]
            by_key[key] = dict(q, min_d=min(clear, default=9.0), chunks=chunks)
            for c in chunks:
                row = (c["distance"], c["source"] in q["relevant"])
                (borderline if c["source"] in unsure else pairs).append(row)
                if c["source"] not in unsure and c["source"] not in GENERIC_SOURCES:
                    dom_pairs.append(row)
        table = [_score(pairs, by_key, t) for t in THRESHOLDS]
        top = max(table, key=lambda s: (round(s["f05"], 6), -s["t"]))
        format_results[fname] = (pairs, borderline, by_key, table, top)
        format_results[fname + " (domain-specific pairs)"] = dom_pairs
        if best is None or top["f05"] > best[1]["f05"]:
            best = (fname, top)

    fname, top = best
    pairs, borderline, by_key, table, _ = format_results[fname]
    dom_pairs = format_results[fname + " (domain-specific pairs)"]
    format_results = {k: v for k, v in format_results.items() if not k.endswith("(domain-specific pairs)")}
    out += ["## After: one query per requirement", ""]
    for name, (_p, _b, _k, _t, tp) in format_results.items():
        out.append(f"- `{name}`: best F0.5 {tp['f05']:.3f} at threshold {tp['t']:.2f} "
                   f"(precision {tp['p']:.2f}, recall {tp['r']:.2f})")
    out += ["", f"Chosen format: **{fname}**, top {TOP_K_PER_QUERY} chunks per query.", "",
            f"Relevant pairs: {_stats([d for d, lab in pairs if lab])}",
            f"Irrelevant pairs: {_stats([d for d, lab in pairs if not lab])}",
            f"Borderline pairs (excluded): {_stats([d for d, _ in borderline])}", "",
            _histogram(pairs), "",
            "## Threshold sweep (chosen format)", "",
            "| Threshold | TP | FP | FN | Precision | Recall | F1 | F0.5 | 'Nothing applies' queries that would cite |",
            "|---|---|---|---|---|---|---|---|---|"]
    for s in table:
        if round(s["t"] * 100) % 5 == 0 or s["t"] == top["t"]:
            mark = " **(chosen)**" if s["t"] == top["t"] else ""
            out.append(f"| {s['t']:.2f}{mark} | {s['tp']} | {s['fp']} | {s['fn']} | {s['p']:.2f} | "
                       f"{s['r']:.2f} | {s['f1']:.2f} | {s['f05']:.2f} | {s['false_alarm']} |")
    out += ["", f"**Chosen threshold: {top['t']:.2f}** (best F0.5)."]
    if abs(top["t"] - RELEVANCE_THRESHOLD) > 1e-9:
        out += ["", f"**Note:** the agent currently uses {RELEVANCE_THRESHOLD}; update RELEVANCE_THRESHOLD."]

    # 5a. Same sweep on domain-specific sources only (information only)
    dom_table = [_score(dom_pairs, by_key, t) for t in THRESHOLDS]
    dom_top = max(dom_table, key=lambda s: (round(s["f05"], 6), -s["t"]))
    at_chosen = next(s for s in dom_table if s["t"] == top["t"])
    out += ["", "## Domain-specific sources only (information)", "",
            f"Pairs whose source is not in GENERIC_SOURCES ({', '.join(sorted(GENERIC_SOURCES))}): "
            f"{len([1 for _, lab in dom_pairs if lab])} relevant, {len([1 for _, lab in dom_pairs if not lab])} irrelevant.", "",
            f"- At the chosen threshold {top['t']:.2f}: precision {at_chosen['p']:.2f}, recall {at_chosen['r']:.2f}, "
            f"F0.5 {at_chosen['f05']:.3f} (TP {at_chosen['tp']}, FP {at_chosen['fp']}, FN {at_chosen['fn']}).",
            f"- Best F0.5 on these pairs alone: {dom_top['f05']:.3f} at {dom_top['t']:.2f} "
            f"(precision {dom_top['p']:.2f}, recall {dom_top['r']:.2f})."]

    # 6. Domain applicability: sweep on what the agent can actually cite
    units = {}
    for key, q in by_key.items():
        units.setdefault(q["group"] if q["scenario"] else q["domain"], []).append(q)
    unit_tags = {u: classify_domains([qs[0]["domain"] or u] + [q["text"] for q in qs]) for u, qs in units.items()}
    app_pairs, app_by_key = [], {}
    for u, qs in units.items():
        for q in qs:
            unsure = set(q.get("borderline_sources", []))
            ok = [c for c in q["chunks"] if c["source"] not in unsure and applies(c["source"], unit_tags[u])]
            app_by_key[(q["group"], q["id"])] = dict(q, min_d=min((c["distance"] for c in ok), default=9.0))
            for c in q["chunks"]:
                if c["source"] in unsure:
                    continue
                d = c["distance"] if applies(c["source"], unit_tags[u]) else 9.0  # never citable
                app_pairs.append((d, c["source"] in q["relevant"]))
    app_table = [_score(app_pairs, app_by_key, t) for t in THRESHOLDS]
    app_top = max(app_table, key=lambda s: (round(s["f05"], 6), -s["t"]))
    out += ["", "## With domain applicability (current agent)", "",
            "Each unit is classified with the agent's `classify_domains()`; a pair can only be cited if its "
            "source applies to the unit's tags (`knowledge_base/sources.json`).", "",
            "| Scenario / domain | Domain tags |", "|---|---|"]
    out += [f"| {u} | {', '.join(t) or '(none)'} |" for u, t in unit_tags.items()]
    out += ["", "| Threshold | TP | FP | FN | Precision | Recall | F1 | F0.5 | 'Nothing applies' queries that would cite |",
            "|---|---|---|---|---|---|---|---|---|"]
    for row in app_table:
        if round(row["t"] * 100) % 5 == 0 or row["t"] in (top["t"], app_top["t"]):
            mark = " **(agent)**" if abs(row["t"] - RELEVANCE_THRESHOLD) < 1e-9 else ""
            out.append(f"| {row['t']:.2f}{mark} | {row['tp']} | {row['fp']} | {row['fn']} | {row['p']:.2f} | "
                       f"{row['r']:.2f} | {row['f1']:.2f} | {row['f05']:.2f} | {row['false_alarm']} |")
    at_agent = next(r for r in app_table if abs(r["t"] - RELEVANCE_THRESHOLD) < 1e-9)
    out += ["", f"At the agent's threshold {RELEVANCE_THRESHOLD}: precision {at_agent['p']:.2f}, recall {at_agent['r']:.2f}, "
            f"F0.5 {at_agent['f05']:.3f}. Best F0.5 with applicability: {app_top['f05']:.3f} at {app_top['t']:.2f} "
            f"(precision {app_top['p']:.2f}, recall {app_top['r']:.2f})."]

    # 5b. kb_relevance per scenario, old rule vs current rule
    def old_rule(reqs, relevant):
        matched = {rid for c in relevant for rid in c["matched_requirement_ids"]}
        if not matched:
            return "not_relevant"
        return "relevant" if len(matched) / len(reqs) >= RELEVANT_COVERAGE else "partially_relevant"

    out += ["", f"## kb_relevance per scenario (chosen format, agent threshold {RELEVANCE_THRESHOLD})", "",
            "| Scenario / domain | Requirements | Old rule (any source) | Domain-specific only | Current rule (+ applies to domain) | Generic-baseline matches |",
            "|---|---|---|---|---|---|"]
    for unit, qs in units.items():
        reqs = [{"id": q["id"]} for q in qs]
        merged = merge_retrieval(reqs, [q["chunks"] for q in qs])
        relevant = [c for c in merged if c["distance"] < RELEVANCE_THRESHOLD]
        generic = sorted({rid for c in relevant if c["source"] in GENERIC_SOURCES for rid in c["matched_requirement_ids"]})
        mid = kb_relevance_from(reqs, relevant)
        old = old_rule(reqs, relevant)
        for c in relevant:
            c["applies_to_domain"] = applies(c["source"], unit_tags[unit])
        new = kb_relevance_from(reqs, relevant)
        out.append(f"| {unit} | {len(reqs)} | {old} | {mid} | {new}{' (changed)' if new != mid else ''} | "
                   f"{', '.join(generic) or '-'} |")
    out += ["",
            "## Per-query nearest chunk", "",
            "Nearest chunk for each query in both formats; * marks a distance under that "
            "format's best threshold.", "",
            "| Group | Query | Labelled relevant | " + " | ".join(f"Nearest ({n})" for n in format_results) + " |",
            "|---|---|---|" + "---|" * len(format_results)]
    for key, q in by_key.items():
        lab = ", ".join(q["relevant"]) or "none"
        if q.get("borderline_sources"):
            lab += " (borderline: " + ", ".join(q["borderline_sources"]) + ")"
        cells = []
        for _p, _b, k, _t, tp in format_results.values():
            c = k[key]["chunks"][0]
            cells.append(f"{c['source']} {c['distance']:.3f}{' *' if c['distance'] < tp['t'] else ''}")
        out.append(f"| {key[0]} | {key[1]} | {lab} | " + " | ".join(cells) + " |")

    report = "\n".join(out) + "\n"
    print(report)
    if write:
        OUT.write_text(report, encoding="utf-8")
        print(f"Wrote {OUT}")
    return top["t"]


if __name__ == "__main__":
    main(write="--write" in sys.argv)
